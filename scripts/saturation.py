#!/usr/bin/env python3
"""Corpus saturation: the stopping rule.

"How much data is enough" has no absolute answer but it has an empirical one.
Consume items in scrape order and watch how fast each chunk introduces unseen
unigrams and unseen markers. When that rate collapses, the register is saturated
and more scraping of that source is wasted effort.

Computed PER VARIETY, because sg saturates long before my does and a combined
number would hide exactly the Manglish shortfall this project exists to avoid.
Also per BOARD for Lowyat, because recency-based discovery skews to the hardware
and trading boards -- this is the table that says where to point the scraper next.
"""
import json
import sys
from collections import Counter, defaultdict
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
IN = ROOT / "data" / "processed" / "scored.jsonl"
DOC = ROOT / "docs" / "saturation.md"
CHUNKS = 10

sys.path.insert(0, str(Path(__file__).resolve().parent))
import markers


def curve(rows: list[dict]) -> tuple[list[tuple[int, int, int]], str]:
    """Per chunk: (size, new unigrams, new markers). Verdict from the last chunk."""
    if len(rows) < CHUNKS * 5:
        return [], "too little data to judge"
    vocab: set[str] = set()
    mseen: set[str] = set()
    step = len(rows) // CHUNKS
    rates: list[tuple[int, int, int]] = []
    for i in range(CHUNKS):
        chunk = rows[i * step:(i + 1) * step] if i < CHUNKS - 1 else rows[i * step:]
        nv = nm = 0
        for r in chunk:
            for t in markers.tokens(r["text"]):
                t = t.lower()
                if t not in vocab:
                    vocab.add(t); nv += 1
            for m in r.get("marker_hits", []):
                if m not in mseen:
                    mseen.add(m); nm += 1
        rates.append((len(chunk), nv, nm))

    first = rates[0][1] / max(rates[0][0], 1)
    last = rates[-1][1] / max(rates[-1][0], 1)
    ratio = last / first if first else 0
    if ratio < 0.15:
        verdict = f"SATURATED (new-token rate fell to {ratio:.0%} of opening rate)"
    elif ratio < 0.35:
        verdict = f"approaching saturation ({ratio:.0%} of opening rate)"
    else:
        verdict = f"KEEP SCRAPING (still at {ratio:.0%} of opening rate)"
    return rates, verdict


def section(title: str, rows: list[dict], out: list[str]) -> None:
    rates, verdict = curve(rows)
    dens = [r["marker_score"] for r in rows]
    mean = sum(dens) / len(dens) if dens else 0
    withm = sum(1 for r in rows if r.get("marker_count"))
    out += [f"### {title}", "",
            f"- rows: **{len(rows)}**",
            f"- mean marker_score: **{mean:.4f}**",
            f"- rows with >=1 marker: **{withm} ({withm / len(rows):.0%})**" if rows else "",
            f"- verdict: **{verdict}**", ""]
    if rates:
        out += ["| chunk | rows | new unigrams | new markers |", "|---|---|---|---|"]
        out += [f"| {i + 1} | {n} | {nv} | {nm} |" for i, (n, nv, nm) in enumerate(rates)]
        out.append("")


def main() -> None:
    rows = [json.loads(l) for l in IN.read_text(encoding="utf-8").splitlines() if l.strip()]

    out = ["# Corpus saturation", "",
           "Generated by `scripts/saturation.py`. The stopping rule: when a source's",
           "rate of introducing unseen unigrams collapses relative to its opening rate,",
           "that register is saturated and more scraping of it is wasted.", "",
           f"Total rows: **{len(rows)}**", ""]

    out += ["## By variety", ""]
    for v in ("sg", "my"):
        rs = [r for r in rows if r["variety"] == v]
        if rs:
            section(f"`{v}`", rs, out)
        else:
            out += [f"### `{v}`", "", "- rows: **0** — no data collected yet.", ""]

    out += ["## By source", ""]
    for s in sorted({r["source"] for r in rows}):
        section(f"`{s}`", [r for r in rows if r["source"] == s], out)

    boards = defaultdict(list)
    for r in rows:
        if r.get("board"):
            boards[r["board"]].append(r)
    if boards:
        out += ["## By Lowyat board", "",
                "Recency-based discovery spans every board, and the hardware and trading",
                "boards are written in fairly plain English. This table says where to point",
                "the scraper next: prefer boards with high mean marker_score.", "",
                "| board | rows | mean marker_score | % with marker |", "|---|---|---|---|"]
        for b, rs in sorted(boards.items(), key=lambda kv: -sum(
                x["marker_score"] for x in kv[1]) / len(kv[1])):
            mean = sum(x["marker_score"] for x in rs) / len(rs)
            withm = sum(1 for x in rs if x["marker_count"]) / len(rs)
            out.append(f"| {b} | {len(rs)} | {mean:.4f} | {withm:.0%} |")
        out.append("")
    else:
        out += ["## By Lowyat board", "",
                "No `board` field present. Threads scraped before board recording was added",
                "carry no board tag; re-scraping is not needed for corpus text, but new",
                "scrapes will populate this table.", ""]

    out += ["## Known limitations", "",
            "- Reddit's `replace_more(limit=0)` drops deep comment chains, biasing pairs",
            "  toward top-level replies.",
            "- YouTube cue parents are adjacency, not reply edges; much of it is monologue.",
            "- Lowyat quote->parent resolution matches author plus time-of-day, so two posts",
            "  by the same author in the same minute could mis-link.", ""]

    top = Counter(m for r in rows for m in r.get("marker_hits", [])).most_common(25)
    if top:
        out += ["## Most frequent markers", "",
                ", ".join(f"`{m}` ({n})" for m, n in top), ""]

    DOC.parent.mkdir(parents=True, exist_ok=True)
    DOC.write_text("\n".join(out))
    print(f"[ok] wrote {DOC.relative_to(ROOT)}")
    for v in ("sg", "my"):
        rs = [r for r in rows if r["variety"] == v]
        print(f"  {v}: {len(rs)} rows — {curve(rs)[1] if rs else 'no data'}")


if __name__ == "__main__":
    main()
